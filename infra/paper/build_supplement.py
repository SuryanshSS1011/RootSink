def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--macros", default="paper_artifacts/macros.tex")
    ap.add_argument("--release", default="data/release/dataset.jsonl")
    ap.add_argument("--out", default="docs/SUPPLEMENT.md")
    args = ap.parse_args(argv)
    m = load_macros(Path(args.macros))
    with open(args.release) as fh:
        rows = [json.loads(line) for line in fh]
    m["CHAIN_TYPES"] = chain_types(rows)
    m["EDGE_KINDS"] = edge_kinds(rows)
    text = TEMPLATE
    for name in sorted(set(re.findall(r"\{(\w+)\}", TEMPLATE)), key=len, reverse=True):
        if name not in m:
            raise SystemExit(f"supplement needs macro {name}, which build_macros.py did not write")
        text = text.replace("{" + name + "}", m[name])
    Path(args.out).write_text(text)
    print(f"supplement -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
