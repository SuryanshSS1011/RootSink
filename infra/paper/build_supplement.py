"""Write docs/SUPPLEMENT.md, the paper's supplementary tables (S1-S4), from the same numbers.

The paper keeps to four pages by pointing here for detail. Every number below comes from
paper_artifacts/macros.tex (build_macros.py) or is computed from data/release/dataset.jsonl in this
script, so the supplement and the paper cannot disagree. Generated; never edit by hand.

Usage: build_supplement.py [--macros paper_artifacts/macros.tex] [--out docs/SUPPLEMENT.md]
"""

from __future__ import annotations

import argparse
import collections
import json
import re
from pathlib import Path


def load_macros(path: Path) -> dict[str, str]:
    out = {}
    for name, val in re.findall(r"\\newcommand\{\\(\w+)\}\{(.*)\}\s*$", path.read_text(), re.M):
        val = val.removesuffix("\\xspace")
        val = val.replace("\\%", "%").replace("\\,", " ").replace("--", "–")
        val = re.sub(r"\\cwe\{(\d+)\}", r"CWE-\1", val)
        val = re.sub(r"\\texttt\{([^}]*)\}", r"`\1`", val)
        val = re.sub(r"\\textbf\{([^}]*)\}", r"\1", val)
        out[name] = val
    return out


def chain_types(rows: list[dict], top: int = 15) -> str:
    gold = [r for r in rows if r["label_confidence_tier"] == "gold"]
    by = collections.defaultdict(list)
    for r in gold:
        by[r["chain_string"]].append(r)
    lines = [
        "| chain (root → sink) | records | projects | root hunk-named | root sanitizer | other |",
        "|---|---:|---:|---:|---:|---:|",
    ]

    def kinds(rs):
        c = collections.Counter(r["chain"][0].get("evidence_kind") for r in rs)
        tested, san = c.get("causally-proven", 0), c.get("execution", 0)
        return tested, san, len(rs) - tested - san

    ranked = sorted(by.items(), key=lambda kv: -len(kv[1]))
    for chain, rs in ranked[:top]:
        t, s, o = kinds(rs)
        lines.append(
            f"| {chain.replace('->', ' → ')} | {len(rs)} | {len({r['project'] for r in rs})} "
            f"| {t} | {s} | {o} |"
        )
    rest = [r for _, rs in ranked[top:] for r in rs]
    if rest:
        t, s, o = kinds(rest)
        n_types = len(ranked) - top
        lines.append(
            f"| {n_types} other chain types | {len(rest)} | {len({r['project'] for r in rest})} "
            f"| {t} | {s} | {o} |"
        )
    return "\n".join(lines)


EDGE_LABEL = {
    "mitre-direct": "CanPrecede directly",
    "mitre-inherited": "via a parent of the earlier CWE (inherited)",
    "mitre-transitive": "via a parent of the next CWE (transitive)",
    "mitre-hierarchy": "one CWE is a parent of the other (hierarchy)",
    "catalog-only": "not in CWE; a pair we declare (modeling)",
}


def edge_kinds(rows: list[dict]) -> str:
    """How CWE supports each consecutive pair, over Reproduced-tier records."""
    gold = [r for r in rows if r["label_confidence_tier"] == "gold"]
    per = collections.Counter()
    only_direct = 0
    for r in gold:
        kinds = {e["kind"] for e in (r.get("mitre_chain") or {}).get("edges", [])}
        per.update(kinds)
        only_direct += kinds == {"mitre-direct"}
    lines = ["| how CWE supports a pair | Reproduced-tier records with such a pair |", "|---|---:|"]
    for k in EDGE_LABEL:
        lines.append(f"| {EDGE_LABEL[k]} | {per.get(k, 0)} |")
    lines.append(f"| every pair CanPrecede directly | {only_direct} |")
    return "\n".join(lines)


